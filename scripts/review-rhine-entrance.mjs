import { mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { chromium } from 'playwright'

const baseUrl = process.env.RHINE_REVIEW_URL || 'http://127.0.0.1:5173/#rhine-archive'
const output = new URL('../review/rhine-archive/entrance/', import.meta.url)
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 }, deviceScaleFactor: 1 })
const failures = []
page.on('console', (message) => { if (message.type() === 'error') failures.push(`console: ${message.text()}`) })
page.on('pageerror', (error) => failures.push(`page: ${error.message}`))
page.on('response', (response) => { if (response.status() >= 400) failures.push(`${response.status()}: ${response.url()}`) })

const shot = async (name) => page.screenshot({ path: fileURLToPath(new URL(`${name}.png`, output)) })
await page.goto(baseUrl, { waitUntil: 'networkidle' })
await page.waitForTimeout(1200)
await shot('01-warning')
await page.waitForTimeout(1720)
await shot('02-flash')
await page.waitForTimeout(1400)
await shot('03-logo-seed')
await page.waitForTimeout(1100)
await shot('04-logo-lockup')
await page.waitForTimeout(1200)
await shot('05-login-reveal')
if (!await page.locator('.rhine-login-form button').isDisabled()) failures.push('login unlocked before the form choreography completed')
await page.waitForFunction(() => document.querySelector('.rhine-entrance')?.dataset.entrancePhase === 'login-ready', null, { timeout: 10000 })
await page.waitForTimeout(120)
if (await page.locator('.rhine-login-form button').isDisabled()) failures.push('login remained locked after the form choreography completed')
await shot('06-login-ready')
await page.locator('.rhine-login-form button').click()
await page.waitForTimeout(120)
const invalidFields = await page.locator('.rhine-login-form input:invalid').count()
if (invalidFields !== 2 || await page.locator('.rhine-login').isHidden()) failures.push('empty login did not retain the native validation state')
await page.locator('input[name="rhine-username"]').fill('RHINE')
await page.locator('input[name="rhine-password"]').fill('001')
await page.locator('.rhine-login-form button').click()
await page.waitForTimeout(120)
if (await page.locator('.rhine-login-error').textContent() !== 'INCORRECT USERNAME OR PASSWORD') failures.push('incorrect credentials did not show the login error')
if (await page.locator('.rhine-login').isHidden()) failures.push('incorrect credentials incorrectly entered the site')
await page.locator('input[name="rhine-username"]').fill('Marlsa')
await page.locator('input[name="rhine-password"]').fill('9029')
await page.locator('.rhine-login-form button').click()
await page.waitForTimeout(920)
await shot('07-verifying-access')
await page.waitForFunction(() => document.querySelector('.rhine-entrance')?.dataset.entrancePhase === 'permission-authorized', null, { timeout: 5000 })
await page.waitForTimeout(1280)
const authorizedText = page.locator('.rhine-auth-text')
if (await authorizedText.textContent() !== 'PERMISSION AUTHORIZED') failures.push('authorization copy is incomplete')
if (!await authorizedText.isVisible()) failures.push('authorization copy did not remain visible for its hold')
await shot('08-permission-authorized')
await page.waitForFunction(() => document.querySelector('.rhine-entrance')?.dataset.entrancePhase === 'welcome', null, { timeout: 5000 })
await page.waitForTimeout(650)
await shot('09-welcome-building')
await page.waitForTimeout(1200)
const welcomeCopyVisible = await page.locator('.rhine-welcome > strong').isVisible()
const welcomeTitleVisible = await page.locator('.rhine-welcome > b').isVisible()
const welcomeLogoVisible = await page.locator('.rhine-welcome > svg').isVisible()
if (!welcomeCopyVisible || !welcomeTitleVisible || !welcomeLogoVisible) failures.push('welcome copy or logo disappeared before the readable hold completed')
await shot('10-welcome-complete')
await page.waitForTimeout(300)
if (!await page.locator('.rhine-entrance').count()) failures.push('entrance exited before the welcome hold and collapse completed')
if (await page.locator('.rhine-entry-transition').count()) failures.push('removed entrance transition video is still mounted')
await page.locator('.rhine-main-navigation').waitFor({ state: 'visible', timeout: 9000 })
await page.waitForTimeout(900)
await shot('11-home-entered')
console.log(JSON.stringify({ failures, screenshots: 11 }, null, 2))
await browser.close()
process.exitCode = failures.length ? 1 : 0
